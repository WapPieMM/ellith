create table if not exists public.site_content (
  id integer primary key default 1 check (id = 1),
  name text not null default 'ellith',
  tagline text default 'a little place of magic',
  bio text default 'welcome to my little corner ♡',
  theme text default 'pink',
  avatar_url text default '',
  cover_url text default '',
  background_url text default '',
  music_url text default '',
  updated_at timestamptz default now()
);
insert into public.site_content (id) values (1) on conflict (id) do nothing;

create table if not exists public.contact_links (
  id bigint generated by default as identity primary key,
  label text not null,
  url text not null,
  icon text default 'link',
  note text default '',
  sort_order integer default 0,
  is_active boolean default true,
  created_at timestamptz default now()
);
create table if not exists public.media_assets (
  id bigint generated by default as identity primary key,
  name text not null,
  path text not null,
  url text not null,
  kind text default 'image',
  created_at timestamptz default now()
);

alter table public.site_content enable row level security;
alter table public.contact_links enable row level security;
alter table public.media_assets enable row level security;

drop policy if exists "Public can read site content" on public.site_content;
create policy "Public can read site content" on public.site_content for select using (true);
drop policy if exists "Authenticated admins manage site content" on public.site_content;
create policy "Authenticated admins manage site content" on public.site_content for all to authenticated using (true) with check (true);

drop policy if exists "Public can read active links" on public.contact_links;
create policy "Public can read active links" on public.contact_links for select using (is_active = true);
drop policy if exists "Authenticated admins manage links" on public.contact_links;
create policy "Authenticated admins manage links" on public.contact_links for all to authenticated using (true) with check (true);

drop policy if exists "Public can read media metadata" on public.media_assets;
create policy "Public can read media metadata" on public.media_assets for select using (true);
drop policy if exists "Authenticated admins manage media metadata" on public.media_assets;
create policy "Authenticated admins manage media metadata" on public.media_assets for all to authenticated using (true) with check (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('ellith-media', 'ellith-media', true, 10485760, array['image/jpeg','image/png','image/webp','image/gif','audio/mpeg','audio/mp3'])
on conflict (id) do nothing;

drop policy if exists "Public can view ellith media" on storage.objects;
create policy "Public can view ellith media" on storage.objects for select using (bucket_id = 'ellith-media');
drop policy if exists "Authenticated admins upload ellith media" on storage.objects;
create policy "Authenticated admins upload ellith media" on storage.objects for insert to authenticated with check (bucket_id = 'ellith-media');
drop policy if exists "Authenticated admins update ellith media" on storage.objects;
create policy "Authenticated admins update ellith media" on storage.objects for update to authenticated using (bucket_id = 'ellith-media') with check (bucket_id = 'ellith-media');
drop policy if exists "Authenticated admins delete ellith media" on storage.objects;
create policy "Authenticated admins delete ellith media" on storage.objects for delete to authenticated using (bucket_id = 'ellith-media');

